#!/usr/bin/env python3
"""Generates the second character's Person plugin (slot person2) from src/Person + src/Shared.

The result is a DISTINCT script, not a copy loaded twice:

  namespace AIBody -> AIBody2, class AIBodyPersonPlugin -> AIBodyPerson2Plugin
  PersonIdentity: slot person2, title "AIBody Person 2", character 2
  params "AIBody2 Inbox" / "AIBody2 Outbox" / "AIBody2 Person Version" (derived from the slot)
  load path Custom/Scripts/d0n/AIBody2/AIBodyPerson2.cslist

VaM compiles every .cslist on its own and cannot pass a define to it, so a build-time variant is
the simplest way to share one code base. Output layout (same as inside d0n.AIBodyPerson2.var):

  <out>/AIBodyPerson2.cslist, <out>/Shared/*.cs, <out>/Person/*.cs (main script: Person/AIBodyPerson2.cs)

Usage: python tools/make_person2.py [--out DIR]   (default: build/person2)
       e.g. --out "C:/VaM/Custom/Scripts/d0n/AIBody2" for a loose-file install
"""
from __future__ import annotations

import argparse
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
SOURCE_CSLIST = "AIBodyPerson.cslist"
CSLIST = "AIBodyPerson2.cslist"
FOLDER = "AIBody2"
DEFAULT_OUT = ROOT / "build" / "person2"

BANNER = ("// GENERATED by tools/make_person2.py from src/{src} - do not edit; edit the source instead.\n"
          "// AIBody Person 2 = slot person2 = character 2 (distinct script: namespace AIBody2).\n")

# (pattern, replacement, expected count or None for "any") applied to every file
COMMON = [
    (r"(?m)^namespace AIBody$", "namespace AIBody2", None),
    (r"\bAIBodyPersonPlugin\b", "AIBodyPerson2Plugin", None),
    (r"d0n\.AIBodyPerson\.", "d0n.AIBodyPerson2.", None),
    (r"Custom/Scripts/d0n/AIBody/AIBodyPerson\.cslist", f"Custom/Scripts/d0n/{FOLDER}/{CSLIST}", None),
]
# main script gets its own file name in the variant
RENAME = {"Person/AIBodyPerson.cs": "Person/AIBodyPerson2.cs"}
# file -> extra replacements that must match exactly once
SPECIFIC = {
    "Person/AIBodyPerson.cs": [
        (r"// Slot person1 = character 1\. Add it on character 1's Person atom",
         "// Slot person2 = character 2. Add it on character 2's Person atom"),
        (r"// Character 2 gets the separate package d0n\.AIBodyPerson2 \(slot person2\), generated from these\n"
         r"// sources by tools/make_person2\.py\.",
         "// Character 1 uses the separate package d0n.AIBodyPerson (slot person1); this file is generated\n"
         "// from its sources by tools/make_person2.py."),
    ],
    "Person/PersonIdentity.cs": [
        (r'Slot = Protocol\.Slot1;', "Slot = Protocol.Slot2;"),
        (r'Title = "AIBody Person";', 'Title = "AIBody Person 2";'),
        (r'Character = "character 1";', 'Character = "character 2";'),
        (r'Cslist = "AIBody/AIBodyPerson\.cslist";', f'Cslist = "{FOLDER}/{CSLIST}";'),
    ],
}


def cslist_files() -> list[str]:
    lines = [ln.strip() for ln in (SRC / SOURCE_CSLIST).read_text(encoding="utf-8").splitlines()]
    return [ln for ln in lines if ln and not ln.startswith("//")]


def transform(rel: str, text: str) -> str:
    for pattern, repl, _ in COMMON:
        text = re.sub(pattern, repl, text)
    for pattern, repl in SPECIFIC.get(rel, []):
        text, n = re.subn(pattern, repl, text)
        if n != 1:
            raise SystemExit(f"make_person2: {rel}: expected one match of {pattern!r}, got {n}")
    if "namespace AIBody2" not in text:
        raise SystemExit(f"make_person2: {rel}: no 'namespace AIBody' to rename")
    return BANNER.format(src=rel) + text


def generate(out: Path = DEFAULT_OUT) -> list[str]:
    """Writes the variant into `out` (replacing it). Returns the relative paths, cslist first."""
    files = cslist_files()
    if out.exists():
        shutil.rmtree(out)
    written = []
    for rel in files:
        dest = RENAME.get(rel, rel)
        target = out / dest
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(transform(rel, (SRC / rel).read_text(encoding="utf-8")), encoding="utf-8")
        written.append(dest)
    # No comment line: VaM treats every line of a .cslist as a file path.
    (out / CSLIST).write_text("\n".join(written) + "\n", encoding="utf-8")
    return [CSLIST] + written


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    files = generate(args.out)
    print(f"Wrote {len(files)} files to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
